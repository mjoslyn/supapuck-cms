-- Identities continue after the highest id.
create or replace function public.sync_id_sequences()
returns void
language sql
security definer
set search_path = ''
as $$
  select setval(pg_get_serial_sequence('public.media', 'id'), greatest((select max(id) from public.media), 1));
  select setval(pg_get_serial_sequence('public.terms', 'id'), greatest((select max(id) from public.terms), 1));
  select setval(pg_get_serial_sequence('public.entries', 'id'), greatest((select max(id) from public.entries), 1));
  select setval(pg_get_serial_sequence('public.forms', 'id'), greatest((select max(id) from public.forms), 1));
$$;
revoke execute on function public.sync_id_sequences() from public, anon, authenticated;
drop function public.forms_sync_id_sequence();
select public.sync_id_sequences();

