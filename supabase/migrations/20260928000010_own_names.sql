-- WordPress naming leaves the data model:
-- * imported rows take their WordPress id as their own id (content, URLs like ?member_cat=51 and field
--   values such as image and venue ids refer to them), and the wp_id columns go;
-- * post types and taxonomies get the site's names (src/lib/content/wp-names.ts);
-- * rows of post types WordPress no longer registers are removed.
-- Fields and content are rewritten by re-running the importer.

alter table public.entries disable trigger entries_touch;
alter table public.media disable trigger media_touch;

delete from public.entries where type in ('evl_event', 'guide-days', 'guides', 'evl_partner');

-- Ids can be given explicitly (the importer does); new rows still get the next one.
alter table public.media alter column id set generated by default;
alter table public.entries alter column id set generated by default;
alter table public.terms alter column id set generated by default;

-- Renumber with the foreign keys off: old id -> WordPress id (rows made here, without one, go after the
-- highest). Ids move out of the way first so none is taken twice mid-update.
alter table public.entries drop constraint entries_parent_id_fkey, drop constraint entries_featured_media_id_fkey;
alter table public.revisions drop constraint revisions_entry_id_fkey;
alter table public.terms drop constraint terms_parent_id_fkey;
alter table public.entry_terms drop constraint entry_terms_entry_id_fkey, drop constraint entry_terms_term_id_fkey;

create temporary table media_ids as
  select id as old, coalesce(wp_id, (select max(wp_id) from public.media) + row_number() over (partition by wp_id is null order by id)) as new from public.media;
create temporary table term_ids as
  select id as old, coalesce(wp_id, (select max(wp_id) from public.terms) + row_number() over (partition by wp_id is null order by id)) as new from public.terms;
create temporary table entry_ids as
  select id as old, coalesce(wp_id, (select max(wp_id) from public.entries) + row_number() over (partition by wp_id is null order by id)) as new from public.entries;

update public.media set id = id + 1000000000;
update public.media t set id = m.new from media_ids m where t.id = m.old + 1000000000;
update public.terms set id = id + 1000000000;
update public.terms t set id = m.new from term_ids m where t.id = m.old + 1000000000;
update public.terms t set parent_id = m.new from term_ids m where t.parent_id = m.old;
update public.entries set id = id + 1000000000;
update public.entries t set id = m.new from entry_ids m where t.id = m.old + 1000000000;
update public.entries t set parent_id = m.new from entry_ids m where t.parent_id = m.old;
update public.entries t set featured_media_id = m.new from media_ids m where t.featured_media_id = m.old;
update public.revisions t set entry_id = m.new from entry_ids m where t.entry_id = m.old;
create temporary table links as
  select e.new as entry_id, tm.new as term_id, l.sort from public.entry_terms l join entry_ids e on e.old = l.entry_id join term_ids tm on tm.old = l.term_id;
delete from public.entry_terms;
insert into public.entry_terms (entry_id, term_id, sort) select entry_id, term_id, sort from links;

